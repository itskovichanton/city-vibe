AliasRow = Tuple[str, str, str, str, float]

PC = "product_categories"
PL = "place_categories"
CT = "cities"


def _rows(catalog: str, code: str, why: str, aliases: Iterable[str], weight: float = 1.0) -> List[AliasRow]:
    out: List[AliasRow] = []
    seen: set[str] = set()
    for raw in aliases:
        alias = (raw or "").strip().lower()
        if len(alias) < 2 or alias in seen:
            continue
        seen.add(alias)
        out.append((catalog, code, alias, why, weight))
    return out


